#!/usr/bin/env node
// Generates the fault-code tables for the web app and the Android app from
// shared/dtc/generic-dtc-he.json, so both always show the same text.
//
//   node scripts/gen-dtc.mjs          write both files
//   node scripts/gen-dtc.mjs --check  exit 1 if either file is stale

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(root, "shared/dtc/generic-dtc-he.json");
export const TS_OUT = join(root, "src/domain/dtc-db.generated.ts");
export const KT_OUT = join(root, "android/core/src/main/kotlin/car/doctor/core/catalog/DtcDatabase.kt");

const SEVERITIES = new Set(["info", "low", "medium", "high", "critical"]);
const CODE = /^[PCBU][0-3][0-9A-F]{3}$/;
const HEADER = "Generated by scripts/gen-dtc.mjs from shared/dtc/generic-dtc-he.json. Do not edit by hand.";

export function loadCodes(path = SOURCE) {
  const { codes } = JSON.parse(readFileSync(path, "utf8"));
  const entries = Object.entries(codes).sort(([a], [b]) => a.localeCompare(b));
  for (const [code, { he, severity }] of entries) {
    if (!CODE.test(code)) throw new Error(`bad code ${code}`);
    if (!SEVERITIES.has(severity)) throw new Error(`bad severity for ${code}: ${severity}`);
    if (typeof he !== "string" || he.trim().length < 5) throw new Error(`missing text for ${code}`);
    if (he.includes('"') || he.includes("\\") || he.includes("$")) throw new Error(`unsafe character in ${code}`);
  }
  return entries;
}

export function renderTs(entries) {
  const lines = entries.map(([code, { he, severity }]) => `  ${code}: ["${he}", "${severity}"],`);
  return `// ${HEADER}
import type { Severity } from "./types.ts";

export const DTC_DB: Readonly<Record<string, readonly [string, Severity]>> = {
${lines.join("\n")}
};
`;
}

export function renderKotlin(entries) {
  // Split into chunks so no single JVM method grows near the 64 KB limit.
  const chunks = [];
  for (let i = 0; i < entries.length; i += 120) chunks.push(entries.slice(i, i + 120));
  const enumName = (severity) => severity.toUpperCase();
  const fns = chunks.map(
    (chunk, i) => `private fun part${i}(into: MutableMap<String, DtcText>) {
${chunk
  .map(([code, { he, severity }]) => `    into["${code}"] = DtcText("${he}", Severity.${enumName(severity)})`)
  .join("\n")}
}`,
  );
  return `// ${HEADER}
package car.doctor.core.catalog

import car.doctor.core.model.Severity

internal val DTC_DB: Map<String, DtcText> = HashMap<String, DtcText>(${entries.length * 2}).also { into ->
${chunks.map((_, i) => `    part${i}(into)`).join("\n")}
}

${fns.join("\n\n")}
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const entries = loadCodes();
  const ts = renderTs(entries);
  const kt = renderKotlin(entries);
  if (process.argv.includes("--check")) {
    const stale = [
      [TS_OUT, ts],
      [KT_OUT, kt],
    ].filter(([path, text]) => {
      try {
        return readFileSync(path, "utf8") !== text;
      } catch {
        return true;
      }
    });
    if (stale.length) {
      console.error(`stale: ${stale.map(([p]) => p).join(", ")}. Run: node scripts/gen-dtc.mjs`);
      process.exit(1);
    }
    console.log(`dtc tables up to date (${entries.length} codes)`);
  } else {
    writeFileSync(TS_OUT, ts);
    writeFileSync(KT_OUT, kt);
    console.log(`wrote ${entries.length} codes`);
  }
}
